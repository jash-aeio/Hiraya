import { z } from "zod";

import { checkinDirection, checkinMethod } from "@/db/enums";

/**
 * The check-in contracts (CLAUDE.md R6, R7; docs/SYSTEM_DESIGN.md §5).
 *
 * **This is the Phase 0 subset only (D24).** The scanner is a simulate-scan
 * button, not a camera: `src/lib/qr` does not exist until Phase 3 and the
 * Ed25519 keypair is deliberately empty. What is *not* here is as deliberate as
 * what is — there is no `token` field, because an unsigned token path is the
 * exact shape R5 forbids and it would have to be deleted rather than extended.
 *
 * Shaped so Phase 3 **extends** it (docs/WORKSTREAMS.md §5, J-02):
 *
 *   - `jti` is already the idempotency key it will be in Phase 3, generated by
 *     the client per scan. Replaying the same scan is a no-op now, before there
 *     is a queue to replay it from (R6) — the constraint that enforces it,
 *     `checkins_event_profile_jti_key`, is already in the schema.
 *   - `profileId` is supplied by the officer's device now and *derived from the
 *     verified token* in Phase 3. That is the one field that changes meaning,
 *     and it changes from trusted-input to verified-fact, never the reverse.
 *   - `checkinResultSchema` is per-item from the start, so `POST /checkins/sync`
 *     in Phase 3 is an array of these and not a second result vocabulary.
 */

export const checkinMethodSchema = z.enum(checkinMethod.enumValues);
export const checkinDirectionSchema = z.enum(checkinDirection.enumValues);

export const recordCheckinBodySchema = z.object({
  eventId: z.uuid(),
  profileId: z.uuid(),
  /**
   * The scan's identity. Phase 3 reads it from the signed token's `jti`; Phase 0
   * generates a UUID on the device. Either way it is what makes a replay a
   * no-op, so it is required rather than server-generated — a server-generated
   * id would make every retry a new check-in.
   */
  jti: z.uuid(),
  /**
   * When the device recorded the scan, which is not when the server received it:
   * a queued scan syncs minutes or hours later, and the attendance record has to
   * say when the learner was actually at the gate.
   */
  scannedAt: z.iso.datetime(),
  deviceId: z.string().max(200).optional(),
  direction: checkinDirectionSchema.default("in"),
  /** Phase 0 writes `officer_scan`; `manual` is a Phase 3 adviser path (audited). */
  method: checkinMethodSchema.default("officer_scan"),
});

export type RecordCheckinBody = z.infer<typeof recordCheckinBodySchema>;

/**
 * `duplicate` is a success, not a failure (src/lib/errors.ts maps
 * DUPLICATE_CHECKIN to 200). Scanning the same learner twice means the officer
 * did nothing wrong, and a red screen at the gate teaches them to distrust the
 * scanner. It returns the *original* check-in id and `xpAwarded: 0`.
 */
export const checkinResultStatusSchema = z.enum(["accepted", "duplicate", "rejected"]);

export type CheckinResultStatus = z.infer<typeof checkinResultStatusSchema>;

export const checkinResultSchema = z.object({
  jti: z.uuid(),
  profileId: z.uuid(),
  status: checkinResultStatusSchema,
  checkinId: z.uuid().nullable(),
  /**
   * What the ledger row written with this check-in was worth — 0 for a
   * duplicate or a rejection. It comes back from the write rather than being
   * assumed by the client, because the point value is an `xp_rules` row the
   * SSLG adviser sets and can change (FR-5.3), and because the XP and the
   * check-in commit together or not at all (D18).
   */
  xpAwarded: z.number().int().nonnegative(),
  /** An error code from src/lib/errors.ts when `status` is `rejected`. */
  reason: z.string().nullable(),
});

export type CheckinResult = z.infer<typeof checkinResultSchema>;

export const recordCheckinResponseSchema = z.object({
  result: checkinResultSchema,
});

export type RecordCheckinResponse = z.infer<typeof recordCheckinResponseSchema>;

// ---------------------------------------------------------------------------
// The officer's event picker
// ---------------------------------------------------------------------------

/**
 * `GET /checkin/events` — the events this officer may scan for right now.
 *
 * A scanner that opens on a list of every event in the school is a scanner that
 * checks learners into the wrong one. The window is the event's own, widened by
 * the grace the service allows; outside it a scan is `SCAN_OUTSIDE_EVENT_WINDOW`
 * and needs adviser review rather than silently counting.
 */
export const scannableEventSchema = z.object({
  id: z.uuid(),
  title: z.string(),
  startsAt: z.iso.datetime(),
  endsAt: z.iso.datetime(),
  venue: z.string().nullable(),
  orgName: z.string(),
  /** False while the event is still hours away — shown, but not scannable yet. */
  scannableNow: z.boolean(),
});

export type ScannableEvent = z.infer<typeof scannableEventSchema>;

export const listScannableEventsResponseSchema = z.object({
  events: z.array(scannableEventSchema),
});

export type ListScannableEventsResponse = z.infer<typeof listScannableEventsResponseSchema>;
